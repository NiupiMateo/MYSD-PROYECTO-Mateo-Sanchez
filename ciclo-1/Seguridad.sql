--- Seguridad

CREATE ROLE rol_administrador;
CREATE ROLE rol_entrenador;
CREATE ROLE rol_gerente;

--- Nadie usa los servicios sin permiso
REVOKE ALL ON ALL ROUTINES IN SCHEMA PA_ADMINISTRADOR FROM PUBLIC;
REVOKE ALL ON ALL ROUTINES IN SCHEMA PA_ENTRENADOR FROM PUBLIC;
REVOKE ALL ON ALL ROUTINES IN SCHEMA PA_GERENTE FROM PUBLIC;

--- Administrador
GRANT USAGE ON SCHEMA PA_ADMINISTRADOR TO rol_administrador;
GRANT EXECUTE ON ALL ROUTINES IN SCHEMA PA_ADMINISTRADOR TO rol_administrador;

--- Entrenador
GRANT USAGE ON SCHEMA PA_ENTRENADOR TO rol_entrenador;
GRANT EXECUTE ON ALL ROUTINES IN SCHEMA PA_ENTRENADOR TO rol_entrenador;

--- Gerente
GRANT USAGE ON SCHEMA PA_GERENTE TO rol_gerente;
GRANT EXECUTE ON ALL ROUTINES IN SCHEMA PA_GERENTE TO rol_gerente;
